import { expect } from "@std/expect";
import { describe, it } from "@std/testing/bdd";
import { SchemaGenerator } from "../src/schema-generator.ts";
import { asObjectSchema, getTypeFromCode } from "./utils.ts";

/**
 * A verb's declared result rides a second type parameter on `Stream`
 * (verb contract WS-C/C1) and is emitted into the durable schema under the
 * `result` dialect keyword (C3), sibling to the `asCell: ["stream"]` marker.
 * Both come off the same type check: a property recognized as a stream gets
 * the marker AND the result schema, or is skipped entirely — there is no
 * state where the marker lands and the result schema does not.
 *
 * This file replaces C1's pin that a returning verb and a value-less one
 * emit byte-identical schemas. That pin existed to be MOVED by C3; these
 * tests are the move.
 */
describe("Stream with a declared result", () => {
  async function schemaFor(code: string) {
    const { type, checker, typeNode } = await getTypeFromCode(
      code,
      "SchemaRoot",
    );
    return asObjectSchema(
      new SchemaGenerator().generateSchema(type, checker, typeNode),
    );
  }

  it("emits the declared result under the `result` keyword beside the marker", async () => {
    const schema = await schemaFor(`
interface AddTopic {
  title: string;
}

interface TopicRef {
  topic: { fid: string };
}

interface SchemaRoot {
  returning: Stream<AddTopic, TopicRef>;
}
`);

    const returning = asObjectSchema(
      (asObjectSchema(schema).properties as Record<string, unknown>)
        .returning,
    );

    // The stream's own schema stays what a caller SENDS: the event `$ref`
    // with the marker. `cf piece verbs` publishes exactly this as the input
    // schema and `piece call` validates payloads against it, so the result
    // must ride BESIDE it, never replace or leak into it.
    expect(returning.$ref).toBe("#/$defs/AddTopic");
    expect(returning.asCell).toEqual(["stream"]);
    expect(returning.result).toEqual({ $ref: "#/$defs/TopicRef" });

    // The result type is hoisted like any named type, and generated by the
    // normal type→schema machinery — LEFT OPEN: no additionalProperties
    // beyond what the type itself demands.
    const defs = asObjectSchema(schema).$defs as Record<string, unknown>;
    expect(Object.keys(defs).toSorted()).toEqual(["AddTopic", "TopicRef"]);
    const topicRef = asObjectSchema(defs.TopicRef);
    expect(topicRef.properties).toEqual({
      topic: {
        type: "object",
        properties: { fid: { type: "string" } },
        required: ["fid"],
      },
    });
    expect(JSON.stringify(topicRef)).not.toContain("additionalProperties");
  });

  it("emits the empty-object receipt for a value-less verb, not the void sentinel", async () => {
    const schema = await schemaFor(`
interface AddTopic {
  title: string;
}

interface SchemaRoot {
  valueLess: Stream<AddTopic>;
  explicitVoid: Stream<AddTopic, void>;
}
`);

    const properties = asObjectSchema(schema).properties as Record<
      string,
      Record<string, unknown> | undefined
    >;

    // `{ type: "object", properties: {} }` describes the `{}` receipt the
    // runtime actually writes. The generic void sentinel
    // (`{ asCell: ["opaque"] }`) would instead be a WRAPPER claim — "the
    // result is an opaque cell" — handing readback a cell to resolve.
    // `additionalProperties` stays undefined: the compat checker reads
    // `additionalProperties ?? true`, and emitting `false` would freeze a
    // verb as value-less forever.
    const expected = { type: "object", properties: {} };
    expect(properties.valueLess?.result).toEqual(expected);
    expect(properties.explicitVoid?.result).toEqual(expected);
    expect(properties.valueLess?.asCell).toEqual(["stream"]);
  });

  it("distinguishes a returning verb from a value-less one — moving C1's pin", async () => {
    const schema = await schemaFor(`
interface AddTopic {
  title: string;
}

interface TopicRef {
  topic: { fid: string };
}

interface SchemaRoot {
  valueLess: Stream<AddTopic>;
  returning: Stream<AddTopic, TopicRef>;
}
`);

    const properties = asObjectSchema(schema).properties as Record<
      string,
      Record<string, unknown> | undefined
    >;

    // C1 pinned these as byte-identical so C3 would have a baseline to move
    // rather than a belief to check. This is the move: the two verbs now
    // differ in exactly one place — the result keyword.
    expect(properties.returning).not.toEqual(properties.valueLess);
    expect({ ...properties.returning, result: undefined }).toEqual(
      { ...properties.valueLess, result: undefined },
    );
    expect(properties.valueLess?.result).toEqual({
      type: "object",
      properties: {},
    });
    expect(properties.returning?.result).toEqual({
      $ref: "#/$defs/TopicRef",
    });
  });

  it("survives an alias that carries the result — type MyVerb = Stream<E, R>", async () => {
    const schema = await schemaFor(`
interface AddTopic {
  title: string;
}

interface TopicRef {
  topic: { fid: string };
}

type MyVerb = Stream<AddTopic, TopicRef>;

interface SchemaRoot {
  aliased: MyVerb;
}
`);

    const aliased = asObjectSchema(
      (asObjectSchema(schema).properties as Record<string, unknown>).aliased,
    );
    expect(aliased.asCell).toEqual(["stream"]);
    expect(aliased.result).toEqual({ $ref: "#/$defs/TopicRef" });
  });
});
